// 목록에서 겹치지 않게 n개 무작위로 뽑기 (exclude에 있는 것은 빼고 뽑음)
export const pickSome = (list, n, exclude) => {
  const pool = list.filter((x) => !exclude.includes(x))
  const picked = []
  while (picked.length < n && pool.length > 0) {
    const i = Math.floor(Math.random() * pool.length)
    picked.push(pool[i])
    pool.splice(i, 1)
  }
  return picked
}
